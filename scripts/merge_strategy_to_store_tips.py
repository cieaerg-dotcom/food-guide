def main():
    with open(UNIFIED_JSON, "r", encoding="utf-8") as f:
        stores = json.load(f)

    updated_count = 0
    for s in stores:
        name = s.get("name", "")
        for target_name, new_tips in STORE_TIPS_ENHANCEMENT.items():
            if target_name in name:
                s["tips"] = new_tips
                updated_count += 1
                print(f"✅ 已注入精華避坑至 [{s.get('uid')}] {name}")
                break

    with open(UNIFIED_JSON, "w", encoding="utf-8") as f:
        json.dump(stores, f, ensure_ascii=False, indent=2)

    print(f"\n成功完成 {updated_count} 間店家的 tips 避坑重點整合！")

if __name__ == "__main__":
    main()
