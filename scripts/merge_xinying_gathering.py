def main():
    # 1. 寫入單獨結構化檔案
    with open(OUTPUT_NEW_JSON, "w", encoding="utf-8") as f:
        json.dump(NEW_STORES, f, ensure_ascii=False, indent=2)
    print(f"已儲存新營聚餐日料結構化資料: {OUTPUT_NEW_JSON} ({len(NEW_STORES)} 間)")

    # 2. 讀取並合併進 taiwan_food_guides_unified.json
    with open(UNIFIED_JSON, "r", encoding="utf-8") as f:
        unified_stores = json.load(f)

    existing_names = {s["name"] for s in unified_stores}
    
    # 更新已有店家情報（青鮨、禾沐）
    for s in unified_stores:
        if "青鮨" in s["name"]:
            s["tips"] += " 【聚餐與預約注意】脆友分享：高階無菜單 Omakase 需提早預約（約3000元/人），座位主要為吧檯板前，適合精緻聚餐或老饕慶祝；若是大批親友人數較多需提早包場確認。"
            s["tags"].extend(["Omakase", "高檔日料", "板前料理"])
            s["tags"] = list(set(s["tags"]))
        elif "禾沐" in s["name"]:
            s["tips"] += " 【新營聚餐超推】脆友一致狂推新營聚餐日料首選！相較於吧檯為主的樸拾與青鮨，禾沐內用空間更寬敞明亮、適合多人圓桌或併桌，CP值極高。"
            s["tags"].extend(["新營聚餐日料首選", "環境寬敞"])
            s["tags"] = list(set(s["tags"]))

    added_count = 0
    for ns in NEW_STORES:
        if ns["name"] not in existing_names:
            unified_stores.append(ns)
            added_count += 1
            print(f"新增店家: [{ns['uid']}] {ns['name']}")

    with open(UNIFIED_JSON, "w", encoding="utf-8") as f:
        json.dump(unified_stores, f, ensure_ascii=False, indent=2)

    print(f"成功更新全台美食資料庫，新增 {added_count} 間，目前總計 {len(unified_stores)} 間店家。")

if __name__ == "__main__":
    main()
